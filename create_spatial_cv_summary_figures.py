
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import os

# --- Centralized Logging Setup ---
import logging
from pathlib import Path
LOG_DIR = Path('wildfire_results')
LOG_DIR.mkdir(exist_ok=True)
LOG_FILE = LOG_DIR / f'spatial_cv_summary_figures_{pd.Timestamp.now().strftime("%Y%m%d_%H%M%S")}.log'
logging.basicConfig(
    filename=LOG_FILE,
    filemode='w',
    level=logging.INFO,
    format='%(asctime)s | %(levelname)s | %(message)s'
)
console = logging.StreamHandler()
console.setLevel(logging.INFO)
formatter = logging.Formatter('%(asctime)s | %(levelname)s | %(message)s')
console.setFormatter(formatter)
logging.getLogger('').addHandler(console)

# --- Pipeline Configuration Logging ---
CONFIG_LOG = LOG_DIR / 'spatial_cv_summary_figures_config.txt'
with open(CONFIG_LOG, 'w') as f:
    f.write("# Spatial CV Summary Figures Configuration\n")
    f.write(f"Run timestamp: {pd.Timestamp.now().isoformat()}\n")
    f.write("Input: corrected_spatial_cv_results/corrected_spatial_cv_results.csv\n")
    f.write("Output: figures/ (summary figures, logs)\n")
    f.write("Key Steps: summary chart generation, top configuration visualization\n")
    f.write("Hyperparameters: see code for plotting settings\n")

# --- Error Handling Decorator ---
def log_exceptions(func):
    def wrapper(*args, **kwargs):
        try:
            return func(*args, **kwargs)
        except Exception as e:
            logging.error(f"Exception in {func.__name__}: {e}", exc_info=True)
            raise
    return wrapper

# Ensure output directory exists
os.makedirs('figures', exist_ok=True)

# Load results
csv_path = "corrected_spatial_cv_results/corrected_spatial_cv_results.csv"
df = pd.read_csv(csv_path)

# --- Top 10 Configurations Summary Chart (UNIQUE - not duplicated in thesis_all_figures.py) ---
top_configs = df.sort_values('spatial_auc_mean', ascending=False).head(10)
plt.figure(figsize=(10,6))
ax = sns.barplot(y=top_configs['configuration'] + ' + ' + top_configs['algorithm'], x=top_configs['spatial_auc_mean'], palette='Blues_d')
for i, (auc, f1) in enumerate(zip(top_configs['spatial_auc_mean'], top_configs['spatial_f1_mean'])):
    ax.text(auc+0.001, i, f"AUC={auc:.4f}\nF1={f1:.4f}", va='center', fontsize=9)
plt.xlabel('Mean AUC')
plt.title('Top 10 Spatial CV Configurations (AUC, F1)')
plt.tight_layout()
plt.savefig('figures/spatial_cv_top10_configurations.png', dpi=300)
plt.close()

print('Saved: figures/spatial_cv_top10_configurations.png')
print('Note: Algorithm performance chart already generated by thesis_all_figures.py as algorithm_comparison.png')
